"""Snyk SBOM -> ServiceNow upload utility (single-file distribution).

This is a self-contained build (generated by build_single_file.py) that combines
the entire application into one module for easy delivery. It exports a Software
Bill of Materials (SBOM) from Snyk (or accepts one produced by the Snyk CLI) and
uploads it to ServiceNow Vulnerability Response.

Two run modes (RUN_MODE):
  * SNYK_API (default) - call the Snyk REST API to generate SBOM(s) for a
    Project, Target, or whole Organization (SNOW_APPLICATION_SCOPE), then upload
    each to ServiceNow.
  * SNYK_CLI - upload an SBOM file you produced with the Snyk CLI, passed via
    --sbom-file-path.

Configuration is environment-variable driven (a local .env file is loaded when
present). See the bundled README / .env.example for the full variable list.

The dependency block above is PEP 723 inline script metadata: run with a
compatible runner to auto-provision dependencies, e.g.:
    uv run snyk_sbom_to_servicenow.py
    pipx run snyk_sbom_to_servicenow.py
Or install the dependencies yourself and use plain Python:
    pip install -r requirements.txt
    python snyk_sbom_to_servicenow.py

DO NOT EDIT THIS FILE BY HAND - it is generated from the app/ package by
build_single_file.py. Edit the modules under app/ and re-run the builder.

Exit codes:
    0  Success
    1  Configuration Error
    2  Authentication Failure
    3  SBOM Generation Failure
    4  ServiceNow Upload Failure
    5  Unexpected Exception
"""

